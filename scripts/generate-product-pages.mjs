import { readFile, writeFile, mkdir, unlink, rmdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const origin = "https://thewear.iqbalsweets.com.pk";
const output = path.join(root, "products");
const manifestPath = path.join(output, ".generated-product-pages.json");
const generatedMarker = "<!-- Generated by scripts/generate-product-pages.mjs -->";
const fallbackImages = {
  BzhcMdcVSsWQASmCTRf1: "assets/products/cap-02.png",
  EB95kmML9igUI58gxYlp: "assets/products/cap-01.png",
  G5r6fGh2SFtQqGgGkrt3: "assets/products/cap-03.png",
  w2yy1HCcbVNN92CGbPXi: "assets/products/cap-04.png"
};

function htmlEscape(value) {
  return String(value).replace(/[&<>"']/g, function (c) {
    return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c];
  });
}

function jsonForScript(value) {
  return JSON.stringify(value)
    .replace(/</g, "\\u003c")
    .replace(/>/g, "\\u003e")
    .replace(/&/g, "\\u0026")
    .replace(/\u2028/g, "\\u2028")
    .replace(/\u2029/g, "\\u2029");
}

function decodeValue(value) {
  if (!value || typeof value !== "object") return undefined;
  if ("stringValue" in value) return value.stringValue;
  if ("integerValue" in value) return Number(value.integerValue);
  if ("doubleValue" in value) return Number(value.doubleValue);
  if ("booleanValue" in value) return value.booleanValue;
  if ("timestampValue" in value) return value.timestampValue;
  if ("nullValue" in value) return null;
  if ("arrayValue" in value) return (value.arrayValue.values || []).map(decodeValue);
  if ("mapValue" in value) return decodeFields(value.mapValue.fields || {});
  return undefined;
}

function decodeFields(fields) {
  return Object.fromEntries(Object.entries(fields).map(function (entry) {
    return [entry[0], decodeValue(entry[1])];
  }));
}

async function getProducts() {
  const config = await readFile(path.join(root, "firebase", "firebase-config.js"), "utf8");
  const projectId = config.match(/\bprojectId\s*:\s*["']([^"']+)["']/)?.[1];
  if (!projectId) throw new Error("Could not read projectId from Firebase config.");

  const collectionUrl = new URL(
    "https://firestore.googleapis.com/v1/projects/" +
    encodeURIComponent(projectId) + "/databases/%28default%29/documents/products"
  );
  const products = [];
  let pageToken = "";
  do {
    const url = new URL(collectionUrl);
    url.searchParams.set("pageSize", "1000");
    if (pageToken) url.searchParams.set("pageToken", pageToken);
    const response = await fetch(url);
    if (!response.ok) {
      throw new Error("Firestore product read failed (" + response.status + "): " + await response.text());
    }
    const page = await response.json();
    for (const document of page.documents || []) {
      const id = document.name.split("/").at(-1);
      if (!id || id === "." || id === ".." || id.includes("/")) {
        throw new Error("Firestore returned an invalid product document ID.");
      }
      products.push(Object.assign(decodeFields(document.fields || {}), { id: id }));
    }
    pageToken = page.nextPageToken || "";
  } while (pageToken);
  return products;
}

function imageUrl(product) {
  const image = product.image || fallbackImages[product.id] || "";
  if (!image) return "";
  try { return new URL(image, origin + "/").href; } catch { return ""; }
}

function pageUrl(product) {
  return origin + "/products/" + encodeURIComponent(product.id) + "/";
}

function renderProduct(product, template) {
  const name = typeof product.name === "string" ? product.name.trim() : "";
  const description = typeof product.description === "string" ? product.description.trim() : "";
  const price = Number(product.price);
  const stockValue = Number(product.stock ?? 0);
  const stock = Number.isFinite(stockValue) ? stockValue : 0;
  const image = imageUrl(product);
  const url = pageUrl(product);

  if (!product.id || !name || !Number.isFinite(price) || price <= 0) {
    throw new Error("Product " + (product.id || "(missing ID)") + " has missing name or invalid price.");
  }

  const schema = {
    "@context": "https://schema.org",
    "@type": "Product",
    "@id": url + "#product",
    productID: String(product.id),
    name: name,
    url: url,
    offers: {
      "@type": "Offer",
      url: url,
      price: price,
      priceCurrency: "PKR",
      availability: stock > 0
        ? "https://schema.org/InStock"
        : "https://schema.org/OutOfStock"
    }
  };
  if (description) schema.description = description;
  if (image) schema.image = [image];

  let html = template.replace("<!-- GENERATED_PRODUCT_JSONLD -->",
    '<script id="product-jsonld" type="application/ld+json">' + jsonForScript(schema) + "</script>");
  const values = {
    "__PRODUCT_TITLE__": htmlEscape(name + " | THE WEAR"),
    "__PRODUCT_DESCRIPTION__": htmlEscape(description || "Shop quality fashion products from THE WEAR in Pakistan."),
    "__PRODUCT_URL__": htmlEscape(url),
    "__PRODUCT_IMAGE__": htmlEscape(image),
    "__PRODUCT_IMAGE_ALT__": htmlEscape(name),
    "__PRODUCT_NAME__": htmlEscape(name),
    "__PRODUCT_DESCRIPTION_TEXT__": htmlEscape(description),
    "__PRODUCT_CATEGORY__": htmlEscape(product.category || ""),
    "__PRODUCT_PRICE__": new Intl.NumberFormat("en-PK").format(price),
    "__PRODUCT_OLD_PRICE__": product.oldPrice && Number.isFinite(Number(product.oldPrice))
      ? "Rs. " + new Intl.NumberFormat("en-PK").format(Number(product.oldPrice)) : "",
    "__PRODUCT_STOCK__": stock > 0 ? stock + " available" : "Out of Stock",
    "__PRODUCT_ID__": htmlEscape(product.id)
  };
  for (const [token, value] of Object.entries(values)) html = html.replaceAll(token, value);

  return html.replace(/\b(href|src)="([^"]*)"/g, function (attribute, name, value) {
    if (/^(?:https?:|\/|#|mailto:|tel:|data:)/i.test(value)) return attribute;
    return name + '="/' + value + '"';
  });
}

function renderShopCard(product) {
  const name = typeof product.name === "string" ? product.name.trim() : "";
  const category = typeof product.category === "string" ? product.category : "";
  const price = Number(product.price);
  const stockValue = Number(product.stock ?? 0);
  const stock = Number.isFinite(stockValue) ? stockValue : 0;
  const image = imageUrl(product);
  const url = "/products/" + encodeURIComponent(product.id) + "/";
  const oldPrice = Number(product.oldPrice);
  return '<article class="card">' +
    '<a href="' + url + '" class="card-media"><img src="' + htmlEscape(image) +
    '" alt="' + htmlEscape(name) + '" loading="lazy"></a>' +
    '<div class="card-body"><div class="card-cat">' + htmlEscape(category) + '</div>' +
    '<h3><a href="' + url + '">' + htmlEscape(name) + '</a></h3>' +
    '<div class="price">Rs. ' + new Intl.NumberFormat("en-PK").format(price) +
    (Number.isFinite(oldPrice) && oldPrice > price
      ? ' <span class="old">Rs. ' + new Intl.NumberFormat("en-PK").format(oldPrice) + "</span>" : "") +
    '</div><div class="stock-status">' + (stock > 0 ? stock + " available" : "Out of Stock") +
    '</div><a class="view" href="' + url + '">View Product</a></div></article>';
}

function replaceMarkerBlock(source, startMarker, endMarker, content) {
  const start = source.indexOf(startMarker);
  const end = source.indexOf(endMarker);
  if (start < 0 || end < start) throw new Error("Missing generated markers: " + startMarker);
  const newline = source.includes("\r\n") ? "\r\n" : "\n";
  const generatedContent = content.replace(/\r?\n/g, newline);
  return source.slice(0, start + startMarker.length) + newline + generatedContent + newline + source.slice(end);
}

async function previousIds() {
  try {
    const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
    return Array.isArray(manifest.ids) ? manifest.ids : [];
  } catch {
    return [];
  }
}

async function removeStalePages(oldIds, currentIds) {
  const current = new Set(currentIds);
  for (const id of oldIds) {
    if (current.has(id)) continue;
    const file = path.join(output, encodeURIComponent(id), "index.html");
    try {
      const content = await readFile(file, "utf8");
      if (!content.includes(generatedMarker)) continue;
      await unlink(file);
      await rmdir(path.dirname(file)).catch(function () {});
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
  }
}

async function main() {
  const products = (await getProducts())
    .filter(function (product) {
      return typeof product.name === "string" && product.name.trim();
    })
    .sort(function (a, b) { return a.name.localeCompare(b.name); });
  const template = await readFile(path.join(root, "scripts", "product-page.template.html"), "utf8");
  const oldIds = await previousIds();
  await mkdir(output, { recursive: true });

  for (const product of products) {
    const directory = path.join(output, encodeURIComponent(product.id));
    await mkdir(directory, { recursive: true });
    const html = renderProduct(product, template).replace("</body>", generatedMarker + "\n</body>");
    await writeFile(path.join(directory, "index.html"), html, "utf8");
  }
  await removeStalePages(oldIds, products.map(function (product) { return product.id; }));
  await writeFile(manifestPath,
    JSON.stringify({ ids: products.map(function (product) { return product.id; }) }, null, 2) + "\n", "utf8");

  const shopPath = path.join(root, "shop.html");
  let shop = await readFile(shopPath, "utf8");
  shop = replaceMarkerBlock(shop, "<!-- GENERATED_PRODUCT_LINKS_START -->",
    "<!-- GENERATED_PRODUCT_LINKS_END -->", products.map(renderShopCard).join("\n"));
  await writeFile(shopPath, shop, "utf8");

  const sitemapPath = path.join(root, "sitemap.xml");
  let sitemap = await readFile(sitemapPath, "utf8");
  const urls = products.map(function (product) {
    return "  <url><loc>" + pageUrl(product).replace(/&/g, "&amp;") + "</loc></url>";
  }).join("\n");
  sitemap = replaceMarkerBlock(sitemap, "<!-- GENERATED_PRODUCT_URLS_START -->",
    "<!-- GENERATED_PRODUCT_URLS_END -->", urls);
  await writeFile(sitemapPath, sitemap, "utf8");

  console.log("Generated " + products.length + " product pages from the public Firestore products collection.");
}

main().catch(function (error) {
  console.error(error);
  process.exitCode = 1;
});